-- Database-level guard for every INSERT/UPDATE to public.comments.body.
-- Term list is kept in parity with src/lib/comment-moderation.ts.

create or replace function public.tizibane_normalize_comment(input_text text)
returns text
language sql
immutable
parallel safe
as $$
  select trim(regexp_replace(
    translate(
      regexp_replace(lower(coalesce(input_text, '')), '[^a-z0-9@!$]+', ' ', 'g'),
      '013457@$!',
      'oieastasi'
    ),
    ' +', ' ', 'g'
  ));
$$;

